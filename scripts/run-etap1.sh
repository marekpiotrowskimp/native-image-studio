#!/bin/zsh
# Etap 1 measurement suite: 10× t2i, reference edits (1..4 refs), img2img, cancel, unload.
# Results: docs/bench/etap1.jsonl (+ console). Images: out/ (git-ignored).
set -uo pipefail
cd "$(dirname "$0")/.."
BIN=.build/xcode/Build/Products/Release/nis-poc
LOG=docs/bench/etap1.jsonl
OUT=out/etap1
run() { echo "\n=== $* ==="; "$BIN" "$@" --bench-log "$LOG" --out "$OUT" 2>&1 | grep -vE "^  step |^Downloading|^Repository" ; }
path_of() { "$BIN" "$@" --bench-log "$LOG" --out "$OUT" 2>&1 | grep "→" | tail -1 | sed 's/.*→ //'; }

run t2i --count 10 --seed 1 --note "10x t2i"

echo "\n=== reference inputs (generated by the model, no private photos) ==="
PERSON=$(path_of t2i --count 1 --seed 7 --prompt "full body photo of a young woman with short black hair standing in a studio, plain grey background, white t-shirt, jeans" --note "ref input: person")
JACKET=$(path_of t2i --count 1 --seed 8 --prompt "product photo of a red leather biker jacket on a white background" --note "ref input: jacket")
DOG=$(path_of t2i --count 1 --seed 9 --prompt "a golden retriever sitting, studio photo, white background" --note "ref input: dog")
BIKE=$(path_of t2i --count 1 --seed 10 --prompt "a vintage turquoise bicycle, product photo, white background" --note "ref input: bicycle")
echo "person=$PERSON jacket=$JACKET dog=$DOG bike=$BIKE"
printf "%s\n" "$PERSON" "$JACKET" "$DOG" "$BIKE" > "$OUT/refs.txt"

run edit --image "$PERSON" --edit-prompt "change the background to a beach at sunset, warm cinematic light" --note "edit 1 image"
run edit --image "$PERSON" --image "$JACKET" --edit-prompt "the woman from image 1 wearing the red leather jacket from image 2" --note "edit 2 refs"
run edit --image "$PERSON" --image "$JACKET" --image "$DOG" --edit-prompt "the woman from image 1 wearing the jacket from image 2, walking the dog from image 3 in a park" --note "edit 3 refs"
run edit --allow-refs 4 --image "$PERSON" --image "$JACKET" --image "$DOG" --image "$BIKE" --edit-prompt "the woman from image 1 wearing the jacket from image 2, with the dog from image 3, riding the bicycle from image 4 in a city street" --note "edit 4 refs"
for s in 0.3 0.6 0.9; do
  run i2i --image "$PERSON" --strength $s --edit-prompt "film photo, warm golden hour light, 35mm grain" --note "i2i strength $s"
done
run cancel --cancel-after-step 1 --note "cancel after step 1"
run cancel --cancel-after-step 2 --note "cancel after step 2"
run unload --note "unload test"
